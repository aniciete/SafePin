-- RLS Policies
CREATE POLICY "Allow public read access to boundaries" ON public.jurisdiction_boundaries FOR SELECT USING (true);
CREATE POLICY "Allow users to view their own profile" ON "public"."users" FOR SELECT TO authenticated USING ((auth.uid() = id));
CREATE POLICY "Allow admins full access to users" ON "public"."users" FOR ALL TO authenticated USING (((SELECT role FROM public.users WHERE id = auth.uid()) = 'admin')) WITH CHECK (((SELECT role FROM public.users WHERE id = auth.uid()) = 'admin'));
CREATE POLICY "Allow anonymous report creation" ON "public"."reports" FOR INSERT TO public WITH CHECK (true);
-- Note: SELECT/UPDATE/DELETE on reports is now handled by the secure RPC functions, not direct RLS policies for users.