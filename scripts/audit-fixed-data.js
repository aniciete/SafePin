// scripts/audit-fixed-data.js
import fs from 'fs/promises';
import path from 'path';

// --- CONFIGURATION ---
const fixedDataDir = path.join(process.cwd(), 'scripts', 'data');
const jurisdictionsFile = path.join(process.cwd(), 'scripts', 'jurisdictions.json');
const auditReportFile = path.join(process.cwd(), 'scripts', '_audit_report_SUCCESS.csv');
// --- END CONFIGURATION ---

async function auditFixedData() {
  console.log('🔵 Starting audit of processed GeoJSON files...');

  try {
    // Load jurisdictions to get city names from PSGC codes
    const jurisdictions = JSON.parse(await fs.readFile(jurisdictionsFile, 'utf-8'));
    const cityLookup = new Map(jurisdictions.map(j => [j.psgc_code, j.city]));
    console.log(`✅ Loaded ${cityLookup.size} jurisdictions for city name lookup.`);

    const allFiles = await fs.readdir(fixedDataDir);
    // Filter for only the files generated by the processing script
    const fixedJsonFiles = allFiles.filter(file => file.endsWith('_FIXED.json'));

    if (fixedJsonFiles.length === 0) {
      console.warn('⚠️ No `_FIXED.json` files found in the `scripts/data` directory to audit.');
      return;
    }

    console.log(`ℹ️ Found ${fixedJsonFiles.length} processed GeoJSON files to audit.`);
    
    const successfulRecords = [];

    for (const fileName of fixedJsonFiles) {
      const filePath = path.join(fixedDataDir, fileName);
      const fileContent = await fs.readFile(filePath, 'utf-8');
      const geoJson = JSON.parse(fileContent);

      if (!geoJson.features) continue;

      for (const feature of geoJson.features) {
        const props = feature.properties;
        const psgc = props.adm4_psgc;
        const barangayName = props.adm4_en;
        
        // Look up the city name using the PSGC code from the fixed file
        const cityName = cityLookup.get(psgc) || '[City not found in master list]';

        successfulRecords.push({
          psgc: psgc,
          barangay: barangayName,
          city: cityName
        });
      }
    }

    console.log('\n🔵 Writing success audit report...');
    const csvHeader = 'psgc,barangay,city\n';
    const csvRows = successfulRecords.map(r => 
        `"${(r.psgc || '').replace(/"/g, '""')}",` +
        `"${(r.barangay || '').replace(/"/g, '""')}",` +
        `"${(r.city || '').replace(/"/g, '""')}"`
    ).join('\n');
    
    await fs.writeFile(auditReportFile, csvHeader + csvRows);
    console.log(`📄 Success! Audit report with ${successfulRecords.length} records created at: ${auditReportFile}`);
    console.log('   You can now compare this with `_mismatch_report.csv` and your original data.');

  } catch (err) {
    console.error('❌ A fatal error occurred during the audit:', err);
  }
}

auditFixedData();